// 真实 Electron 宿主验证：拖入 IPC → 岛内草稿 → 设备 → 等待接收 → 接收卡片 → HTTPS 文件。
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { app, BrowserWindow, webContents, clipboard } = require('electron')
app.disableHardwareAcceleration()
const { LocalSendService } = require('../../dist-electron/transfers/service.js')
const REPO = path.resolve(__dirname, '../..')
const originalCwd = process.cwd()
const output = process.env.TRANSFER_QA_DIR || path.join(os.tmpdir(), 'island-transfer-qa')
let root, peer
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const until = async (fn, timeout = 15000) => {
  const end = Date.now() + timeout
  while (!(await fn())) { if (Date.now() > end) throw new Error('界面状态等待超时'); await wait(80) }
}
const errors = []
app.on('web-contents-created', (_event, contents) => {
  contents.on('console-message', (_e, level, text) => { if (level >= 3 && !text.includes('ERR_CONNECTION_REFUSED')) errors.push(text) })
  contents.on('preload-error', (_e, _p, error) => errors.push(String(error)))
})
;(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'island-transfer-ui-'))
  await fs.mkdir(output, { recursive: true })
  app.setPath('userData', path.join(root, 'profile'))
  await fs.mkdir(app.getPath('userData'), { recursive: true })
  // 不启动 Windows 通知授权或真实通知接口；这里只验证文件传输。
  await fs.writeFile(path.join(app.getPath('userData'), 'settings.json'), JSON.stringify({ idleMode:'float', islandTop:8, miniScale:1, pluginOrder:[], disabledPlugins:['system-notifications'], pluginModes:{'system-notifications':'off'}, checkUpdatesOnLaunch:false }))
  await fs.mkdir(path.join(app.getPath('userData'), 'plugin-data'), { recursive:true })
  await fs.writeFile(path.join(app.getPath('userData'), 'plugin-data', 'system-notifications.json'), JSON.stringify({ __settings:{ windowsEnabled:false, localApiEnabled:false } }))
  await fs.mkdir(path.join(app.getPath('userData'), 'transfers'), { recursive:true })
  await fs.writeFile(path.join(app.getPath('userData'), 'transfers', 'settings.json'), JSON.stringify({ alias:'验收电脑', saveDirectory:path.join(root,'received') }))
  process.chdir(REPO)
  require('../../dist-electron/main.js')
  await app.whenReady()
  await until(() => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('dist/index.html')))
  const host = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('dist/index.html'))
  const js = code => host.webContents.executeJavaScript(code)
  await until(() => js('!!window.dynamicIslandHost'))
  await js('window.dynamicIslandHost.openTransfer()')
  await until(() => webContents.getAllWebContents().find(w => w.getURL().includes('modules/file-transfer/index.html')))
  const view = webContents.getAllWebContents().find(w => w.getURL().includes('modules/file-transfer/index.html'))
  const ui = code => view.executeJavaScript(code).catch(error => { throw new Error(`${error.message}\nUI: ${code}\nConsole: ${errors.join('\n')}`) })
  await until(async () => (await ui('window.islandTransfer.snapshot()')).snapshot?.status === 'running')
  const snapshot = async () => (await ui('window.islandTransfer.snapshot()')).snapshot
  assert.match(await ui('document.title'), /文件传输/)
  assert.match(await ui('document.body.innerText'), /将文件拖到灵动岛/)
  assert.equal(await ui('document.documentElement.scrollWidth > innerWidth'), false)
  await wait(650)
  await fs.writeFile(path.join(output, 'empty.png'), (await view.capturePage()).toPNG())
  const initial = await snapshot()
  // 隔离接收目录，禁止测试写入真实 Downloads。
  await ui('window.islandTransfer.call("close")')
  peer = new LocalSendService({ baseDir:path.join(root,'peer'), saveDirectory:path.join(root,'peer-files'), alias:'测试手机', port:0, discovery:false })
  await peer.start()
  assert.equal(peer.snapshot().status, 'running')
  // 通过真实系统拖放对象从 preload 取得路径，而不是向渲染页暴露 Node。
  const source = path.join(root, '交互验收.txt')
  await fs.writeFile(source, 'Activity Island LocalSend UI check')
  await js('window.dynamicIslandHost.openTransfer()')
  await until(async () => (await js('window.dynamicIslandHost.getState()')).mode === 'custom')
  await ui(`window.islandTransfer.call('connect', ${JSON.stringify('127.0.0.1:' + peer.snapshot().port)})`)
  await ui('window.islandTransfer.call("close")')
  await until(async () => (await js('window.dynamicIslandHost.getState()')).mode !== 'custom')
  await wait(650)
  // Chromium 的文件拖放事件会生成真实 File 对象，经过与资源管理器拖放相同的 preload 路径。
  host.webContents.debugger.attach('1.3')
  const box = await js('(() => { const b=document.querySelector(".island-shell").getBoundingClientRect(); return {x:b.x+b.width/2,y:b.y+30} })()')
  const dragData = { items:[], files:[source], dragOperationsMask:1 }
  await host.webContents.debugger.sendCommand('Input.dispatchDragEvent', { type:'dragEnter', ...box, data:dragData })
  await host.webContents.debugger.sendCommand('Input.dispatchDragEvent', { type:'dragOver', ...box, data:dragData })
  await until(() => js('!document.querySelector(".transfer-drop-preview").hidden'))
  await host.webContents.debugger.sendCommand('Input.dispatchDragEvent', { type:'drop', ...box, data:dragData })
  host.webContents.debugger.detach()
  await until(async () => (await snapshot()).draft.length === 1)
  const secondSource = path.join(root, '可移除的文件.txt')
  await fs.writeFile(secondSource, 'second')
  // 第二次拖放追加已有选择，逐项移除不会丢失第一个文件。
  view.debugger.attach('1.3')
  const secondDrag = { items:[], files:[secondSource], dragOperationsMask:1 }
  for (const type of ['dragEnter','dragOver','drop']) await view.debugger.sendCommand('Input.dispatchDragEvent', { type, x:180, y:130, data:secondDrag })
  view.debugger.detach()
  await until(async () => (await snapshot()).draft.length === 2)
  await until(() => ui('document.querySelectorAll("[data-action=remove]").length === 2'))
  await ui('Array.from(document.querySelectorAll("[data-action=remove]")).find(b=>b.getAttribute("aria-label").includes("可移除")).click()')
  await until(async () => (await snapshot()).draft.length === 1)
  assert.equal((await snapshot()).draft[0].fileName, '交互验收.txt')
  await until(() => ui('document.querySelectorAll("[data-device]:not(:disabled)").length > 0'))
  await wait(200)
  await fs.writeFile(path.join(output, 'selected.png'), (await view.capturePage()).toPNG())
  await ui('Array.from(document.querySelectorAll("[data-device]:not(:disabled)")).find(b=>b.textContent.includes("测试手机")).click()')
  await until(() => peer.snapshot().sessions.some(s => s.state === 'waiting'))
  assert.equal((await fs.readdir(path.join(root,'peer-files'))).length, 0)
  await wait(150)
  await fs.writeFile(path.join(output, 'waiting.png'), (await view.capturePage()).toPNG())
  await ui('window.islandTransfer.call("close")')
  await until(() => js('!document.querySelector(".transfer-progress").hidden'))
  assert.match(await js('document.querySelector(".transfer-progress").textContent'), /等待/)
  await js('document.querySelector(".transfer-progress").click()')
  peer.accept(peer.snapshot().sessions[0].id)
  await until(async () => (await snapshot()).sessions.some(s => s.state === 'completed'))
  assert.equal(await fs.readFile(path.join(root,'peer-files','交互验收.txt'),'utf8'), 'Activity Island LocalSend UI check')
  // 接收端：外部端点请求自动展开接收卡片，点击拒绝可以结束任务。
  await peer.connect(`127.0.0.1:${initial.port}`)
  await peer.selectFiles([source])
  await ui('window.islandTransfer.call("close")')
  await peer.send(peer.snapshot().devices[0].id)
  await until(() => ui('!document.getElementById("incoming").hidden'))
  assert.match(await ui('document.getElementById("incoming").innerText'), /测试手机/)
  assert.match(await ui('document.getElementById("incoming").innerText'), /想向你发送文件/)
  assert.equal(await ui('document.getElementById("send-page").hidden'), true)
  await wait(600)
  await fs.writeFile(path.join(output, 'incoming.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-action=reject]").click()')
  await until(() => peer.snapshot().sessions[0].state === 'rejected')
  // 再次发送，接收端通过真实按钮接受；文件保存在隔离目录。
  const batch = [source]
  for (let i = 0; i < 15; i++) {
    const file = path.join(root, `用于检查多文件列表的长文件名-${i}.txt`)
    await fs.writeFile(file, 'batch')
    batch.push(file)
  }
  await peer.selectFiles(batch)
  await peer.send(peer.snapshot().devices[0].id)
  await until(() => ui('!document.getElementById("incoming").hidden'))
  await until(() => ui('document.querySelectorAll("#incoming .file-row").length === 16'))
  await wait(400)
  await fs.writeFile(path.join(output, 'incoming-many.png'), (await view.capturePage()).toPNG())
  assert.equal(await ui('document.documentElement.scrollWidth > innerWidth'), false)
  assert.equal(await ui('(() => { const b=document.querySelector("[data-action=accept]").getBoundingClientRect(); const c=document.getElementById("content").getBoundingClientRect(); const l=document.querySelector("#incoming .transfer-files"); return b.top>=c.top && b.bottom<=c.bottom && l.scrollHeight>l.clientHeight })()'), true)
  await fs.writeFile(path.join(output, 'incoming-many.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-action=accept]").click()')
  await until(() => peer.snapshot().sessions[0].state === 'completed')
  assert.equal(await fs.readFile(path.join(root,'received','交互验收.txt'),'utf8'), 'Activity Island LocalSend UI check')
  await until(() => ui('document.getElementById("current-task").innerText.includes("传输完成")'))
  await wait(200)
  await fs.writeFile(path.join(output, 'completed.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-page=receive]").click()')
  assert.match(await ui('document.getElementById("receive-page").innerText'), /验收电脑/)
  await fs.writeFile(path.join(output, 'receive.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-page=settings]").click()')
  assert.match(await ui('document.getElementById("settings-page").innerText'), /保存位置/)
  await ui('document.getElementById("rename").click(); document.getElementById("alias").value="我的电脑"; document.getElementById("rename-form").requestSubmit()')
  await until(async () => (await snapshot()).alias === '我的电脑')
  await ui('document.getElementById("history").click()')
  assert.match(await ui('document.getElementById("history-page").innerText'), /传输完成/)
  await ui('document.querySelector("[data-page=send]").click()')
  // 原生文本：真实文本输入 → 设备 → LocalSend preview → 204；无 txt 文件。
  const outgoingText = '你好，来自灵动岛 🌏\nhttps://example.com/?a=1&b=2'
  await ui(`document.querySelector('[data-mode=text]').click(); document.getElementById('message').value=${JSON.stringify(outgoingText)}; document.getElementById('message').dispatchEvent(new Event('input'))`)
  assert.equal(await ui('document.getElementById("text-section").hidden'), false)
  await wait(400)
  await fs.writeFile(path.join(output, 'text-compose.png'), (await view.capturePage()).toPNG())
  await ui('Array.from(document.querySelectorAll("[data-device]:not(:disabled)")).find(b=>b.textContent.includes("测试手机")).click()')
  await until(() => peer.snapshot().sessions[0].state === 'waiting')
  assert.equal(peer.snapshot().sessions[0].files[0].preview, outgoingText)
  peer.accept(peer.snapshot().sessions[0].id)
  await until(async () => (await snapshot()).sessions[0].state === 'completed')
  assert.equal((await fs.readdir(path.join(root,'peer-files'))).length, 1)
  await until(() => ui('document.getElementById("message").value === ""'))
  await ui('document.querySelector("[data-page=send]").click(); document.getElementById("message").value="尚未发送的草稿"; document.getElementById("message").dispatchEvent(new Event("input"))')
  const incomingText = '这是一条来自手机的文本 😊\nhttps://example.com/\n<img src=x onerror="window.previewInjected=true">'
  const incomingId = await peer.sendText(peer.snapshot().devices[0].id, incomingText)
  await until(() => ui('!document.getElementById("incoming").hidden && !!document.querySelector("#incoming .text-preview")'))
  assert.equal(await ui('document.querySelector("#incoming pre").textContent'), incomingText)
  assert.equal(await ui('!!window.previewInjected || !!document.querySelector("#incoming .text-preview img")'), false)
  await wait(400)
  await fs.writeFile(path.join(output, 'text-incoming.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-action=accept-copy]").click()')
  await until(() => peer.snapshot().sessions.find(s => s.id === incomingId).state === 'completed')
  await until(() => clipboard.readText() === incomingText)
  assert.equal(await ui('document.getElementById("message").value'), '尚未发送的草稿')
  assert.equal((await fs.readdir(path.join(root,'received'))).length, 16)
  await until(() => ui('!!document.querySelector("[data-action=copy-text]")'))
  await wait(400)
  await fs.writeFile(path.join(output, 'text-completed.png'), (await view.capturePage()).toPNG())
  await ui('document.querySelector("[data-page=send]").click(); document.querySelector("[data-mode=files]").click()')
  view.debugger.attach('1.3')
  await view.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width:430, height:560, deviceScaleFactor:1, mobile:false })
  assert.equal(await ui('document.documentElement.scrollWidth > innerWidth'), false)
  await wait(200)
  await fs.writeFile(path.join(output, 'narrow.png'), (await view.capturePage()).toPNG())
  await view.debugger.sendCommand('Emulation.clearDeviceMetricsOverride')
  view.debugger.detach()
  await ui('document.getElementById("connect-toggle").click(); document.getElementById("address").value="8.8.8.8"; document.getElementById("connect-form").requestSubmit()')
  await until(() => ui('!document.getElementById("notice").hidden'))
  assert.match(await ui('document.getElementById("notice").innerText'), /局域网/)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ ok:true, checks:['页面与非空','动态面板与窄视口无水平溢出','Chromium 真实文件拖放及 preload 路径提取','追加与逐项移除','文本输入与预览发送','设备选择','接受前不传文件','收起后小岛任务进度与重新展开','真实 HTTPS 双向文件与文本收发','接收请求自动展开','长文件列表与固定接受按钮','接受及拒绝按钮','接收文本预览与复制','发送接收设置导航及改名','传输记录','错误提示','无页面及 preload 错误'], screenshots:output }, null, 2))
})().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => {
  await peer?.stop()
  process.chdir(originalCwd)
  app.exit(process.exitCode || 0)
})
