const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { PluginManager } = require('../../dist-electron/plugins/plugin-manager.js')

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'island-plugin-reserved-'))
try {
  const user = path.join(root, 'plugins')
  const source = path.join(root, 'source')
  fs.mkdirSync(source, { recursive: true })
  fs.writeFileSync(path.join(source, 'index.html'), '<!doctype html>')
  fs.writeFileSync(path.join(source, 'plugin.json'), JSON.stringify({ id: 'system-notifications', name: '重复 ID', version: '1.0.0', entry: 'index.html' }))
  const manager = new PluginManager([user], user, new Set(['system-notifications']))
  assert.throws(() => manager.installDirectory(source), /系统功能/)
  assert.equal(fs.existsSync(path.join(user, 'system-notifications')), false)
  fs.mkdirSync(path.join(user, 'legacy'), { recursive: true })
  fs.cpSync(source, path.join(user, 'legacy'), { recursive: true })
  manager.discover()
  assert.equal(manager.has('system-notifications'), false)
  assert.match(manager.issues()[0].reason, /系统功能/)
  fs.writeFileSync(path.join(source, 'plugin.json'), JSON.stringify({ id: 'ordinary-plugin', name: '普通插件', version: '1.0.0', entry: 'index.html' }))
  manager.installDirectory(source)
  assert.equal(manager.has('ordinary-plugin'), true)
  manager.uninstall('ordinary-plugin')
  assert.equal(manager.has('ordinary-plugin'), false)
  console.log('reserved id and ordinary plugin management passed')
} finally { fs.rmSync(root, { recursive: true, force: true }) }
