// 验证旧版关闭配置升级后，通知与用户插件管理分离且仍能显示。
const { app, BrowserWindow, webContents } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const until = async (fn, timeout = 12000) => {
  const end = Date.now() + timeout
  while (!(await fn())) { if (Date.now() > end) throw new Error('通知界面状态等待超时'); await wait(80) }
}

;(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'island-notification-test-'))
  const profile = path.join(root, 'profile')
  await fs.mkdir(path.join(profile, 'plugin-data'), { recursive: true })
  await fs.writeFile(path.join(profile, 'settings.json'), JSON.stringify({ idleMode: 'float', islandTop: 8, miniScale: 1, disabledPlugins: ['system-notifications'], pluginModes: { 'system-notifications': 'off' }, pluginModesMigrated: true, checkUpdatesOnLaunch: false }))
  await fs.writeFile(path.join(profile, 'plugin-data', 'system-notifications.json'), JSON.stringify({ __settings: { windowsEnabled: false, localApiEnabled: false, alertEnabled: true, ttlInfo: 20 } }))
  app.setPath('userData', profile)
  process.chdir(path.join(__dirname, '../..'))
  require('../../dist-electron/main.js')
  await app.whenReady()
  await until(() => BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('dist/index.html')))
  const host = BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('dist/index.html'))
  const hostJs = code => host.webContents.executeJavaScript(code)
  await until(() => hostJs('!!window.dynamicIslandHost'))
  assert.equal((await hostJs('window.dynamicIslandHost.listPlugins()')).some(item => item.id === 'system-notifications'), false)
  const migrated = JSON.parse(await fs.readFile(path.join(profile, 'settings.json'), 'utf8'))
  assert.equal(migrated.disabledPlugins.includes('system-notifications'), false)
  assert.equal(Object.hasOwn(migrated.pluginModes, 'system-notifications'), false)
  await hostJs('window.dynamicIslandHost.openSettings("notifications")')
  await until(() => BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('console-apps/settings/index.html')))
  const settings = BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('console-apps/settings/index.html'))
  const settingsJs = code => settings.webContents.executeJavaScript(code)
  await until(() => settingsJs('!!window.islandSettings'))
  await until(() => settingsJs('!!document.querySelector("#notif-settings [data-key=ttlInfo]")'))
  assert.equal(await settingsJs('Number(document.querySelector("#notif-settings [data-key=ttlInfo]").value)'), 20)
  const values = await settingsJs('window.islandSettings.notificationSettings()')
  assert.equal(values.values.windowsEnabled, false)
  assert.equal(values.values.localApiEnabled, false)
  assert.equal(values.values.ttlInfo, 20)
  assert.equal((await settingsJs('window.islandSettings.uninstall("system-notifications")')).ok, false)
  assert.equal((await settingsJs('window.islandSettings.setNotificationSettings({ ttlInfo: 21 })')).values.ttlInfo, 21)
  assert.equal((await settingsJs('window.islandSettings.testIngestNotification({title:"通知显示验收",body:"验证码 123456"})')).ok, true)
  await settingsJs('window.islandSettings.close()').catch(() => {})
  await until(() => webContents.getAllWebContents().find(w => w.getURL().includes('modules/system-notifications/index.html')))
  const view = webContents.getAllWebContents().find(w => w.getURL().includes('modules/system-notifications/index.html'))
  await until(() => view.executeJavaScript('document.getElementById("s-title").textContent === "通知显示验收"'))
  await until(async () => (await hostJs('window.dynamicIslandHost.getState()')).visiblePluginIds.includes('system-notifications'))
  await view.executeJavaScript('document.getElementById("small").click()')
  await until(() => view.executeJavaScript('document.getElementById("medium").classList.contains("is-active")'))
  assert.match(await view.executeJavaScript('document.getElementById("medium").innerText'), /123456/)
  console.log('notification builtin migration and display passed')
  app.exit(0)
})().catch(error => { console.error(error); app.exit(1) })
